from math import fsum, isclose
from typing import Self

from pydantic import BaseModel, Field, JsonValue, model_validator

import pandas as pd
import numpy as np
import numpy.typing as npt

# Type alias for overlap matrix representing the similarity/overlap between model outputs
OverlapMatrix = npt.NDArray[np.int32]

class ModelOutput(BaseModel):
    source: str = Field(..., description="Name of the source that generated this hypothesis(es)")
    response: str = Field(..., description="Response generated by the model")

class DataSample(BaseModel):
    scenario_id: str = Field(..., description="Unique identifier for the scenario")
    created_at: str = Field(..., description="Timestamp when the data sample was created in format: YYYY-MM-DD")
    input_message: str = Field(..., description="Input message for the models")
    outputs: list[ModelOutput] = Field(..., description="List of outputs generated by different models for this data sample")

class DataSet(BaseModel):
    samples: list[DataSample] = Field(..., description="List of data samples in the dataset")

    def add_sample(self, sample: DataSample) -> None:
        self.samples.append(sample)

    def get_sample_by_id(self, scenario_id: str) -> DataSample | None:
        for sample in self.samples:
            if sample.scenario_id == scenario_id:
                return sample
        return None
    
    def get_samples_by_source(self, source: str) -> list[DataSample]:
        result = []
        for sample in self.samples:
            for output in sample.outputs:
                if output.source == source:
                    result.append(sample)
                    break
        return result
    
    # TODO: Test whether this produces the correct DataFrame
    def convert_to_dataframe(self) -> pd.DataFrame:
        data = []
        for sample in self.samples:
            for output in sample.outputs:
                data.append({
                    "scenario_id": sample.scenario_id,
                    "created_at": sample.created_at,
                    "input_message": sample.input_message,
                    "source": output.source,
                    "response": output.response
                })
        return pd.DataFrame(data)

class FrameOfDiscernment(BaseModel):
    frame: list[str] = Field(..., description="The frame of discernment for the current scenario.")

class FodOutput(BaseModel):
    hypotheses: dict[str, str] = Field(default_factory=dict, description="Mapping of source -> response from source. For example, 'source 1: <hypothesis of source 1>, source 2: <hypotheses of source 2>, ...")
    frame: FrameOfDiscernment


class FocalSet(BaseModel):
    hypotheses: list[str] = Field(
        ...,
        min_length=1,
        description="A non-empty subset of hypotheses from the frame of discernment.",
    )
    justification: str = Field(
        ...,
        min_length=1,
        description="Explanation of why the source supports this focal set.",
    )
    citations: list[str] = Field(
        ...,
        min_length=1,
        description="Verbatim excerpts from the source text supporting the focal set.",
    )


class SourceFocalSets(BaseModel):
    source: str = Field(..., min_length=1, description="Source identifier from FodOutput.hypotheses.")
    focal_sets: list[FocalSet] = Field(
        ...,
        min_length=1,
        description="Focal sets supported by this source.",
    )


class FocalSetOutput(BaseModel):
    sources: list[SourceFocalSets] = Field(
        default_factory=list,
        description="Focal sets and cited support grouped by source.",
    )
    validation_errors: list[str] = Field(
        default_factory=list,
        description=(
            "Post-generation validation issues found by the focal-set creator. "
            "An empty list means semantic validation passed."
        ),
    )


class FocalSetMass(BaseModel):
    """Mass committed to a non-empty subset, not split across its members."""

    hypotheses: list[str] = Field(min_length=1)
    mass: float = Field(ge=0, le=1, allow_inf_nan=False)
    justification: str = Field(min_length=1)

    @model_validator(mode="after")
    def unique_hypotheses(self) -> Self:
        if any(not h.strip() for h in self.hypotheses):
            raise ValueError("Hypotheses must not be blank")
        if len(set(self.hypotheses)) != len(self.hypotheses):
            raise ValueError("Duplicate hypotheses in a mass subset")
        return self


class SourceMassResponse(BaseModel):
    """LLM-generated masses for the source supplied in one request."""

    masses: list[FocalSetMass] = Field(min_length=1)


class SourceBpa(BaseModel):
    source: str = Field(min_length=1)
    masses: list[FocalSetMass] = Field(min_length=1)

    @model_validator(mode="after")
    def valid_distribution(self) -> Self:
        subsets = [frozenset(entry.hypotheses) for entry in self.masses]
        if len(set(subsets)) != len(subsets):
            raise ValueError("Duplicate mass subsets")
        if not isclose(fsum(entry.mass for entry in self.masses), 1.0,
                       rel_tol=0, abs_tol=1e-6):
            raise ValueError("Masses for each source must sum to one (tolerance 1e-6)")
        return self


class BpaOutput(BaseModel):
    sources: list[SourceBpa] = Field(min_length=1)

    @model_validator(mode="after")
    def unique_sources(self) -> Self:
        sources = [entry.source for entry in self.sources]
        if len(set(sources)) != len(sources):
            raise ValueError("Duplicate BPA sources")
        return self


class CombinedMass(BaseModel):
    """A combined subset mass; [] represents conflict for rules retaining it."""

    hypotheses: list[str]
    mass: float = Field(ge=0, le=1, allow_inf_nan=False)


class CombinedEvidence(BaseModel):
    """Method-neutral distribution, including optional rule-specific diagnostics."""

    frame: FrameOfDiscernment
    sources: list[str] = Field(min_length=1)
    combiner: str = Field(min_length=1)
    masses: list[CombinedMass] = Field(min_length=1)
    conflict_mass: float | None = Field(default=None, ge=0, le=1, allow_inf_nan=False)
    diagnostics: dict[str, JsonValue] = Field(default_factory=dict)

    @model_validator(mode="after")
    def valid_distribution(self) -> Self:
        frame = self.frame.frame
        if not frame or any(not h.strip() for h in frame) or len(set(frame)) != len(frame):
            raise ValueError("Frame must contain unique, non-blank hypotheses")
        if any(not s.strip() for s in self.sources) or len(set(self.sources)) != len(self.sources):
            raise ValueError("Sources must be unique and non-blank")
        subsets = []
        for entry in self.masses:
            subset = frozenset(entry.hypotheses)
            if len(subset) != len(entry.hypotheses) or not subset.issubset(frame):
                raise ValueError("Invalid combined mass subset")
            subsets.append(subset)
        if len(set(subsets)) != len(subsets):
            raise ValueError("Duplicate combined mass subsets")
        if not isclose(fsum(entry.mass for entry in self.masses), 1.0, rel_tol=0, abs_tol=1e-6):
            raise ValueError("Combined masses must sum to one")
        return self
